import assert from "node:assert/strict";
import fs from "node:fs";

const artifact = JSON.parse(fs.readFileSync("experimental/bounded-label-capacity-screen-ownership-refinement1/result-summary.json", "utf8"));
const smoke = JSON.parse(fs.readFileSync("experimental/bounded-label-capacity-screen-ownership-refinement1/actual-product-smoke-summary.json", "utf8"));
assert.equal(artifact.classification, "D. MULTI-COMPONENT BENEFIT CONFIRMED / SINGLE-COMPONENT FORMULATION OPEN");
assert.equal(artifact.variantCount, 3);
assert.equal(artifact.candidateCountBound, 3);
assert.equal(artifact.globalScalingOnly, false);
assert.equal(artifact.productionMetricMutation, false);
assert.equal(artifact.productAuthoritiesChanged, false);
assert.deepEqual(artifact.rows.map(({ fixture }) => fixture), ["canonical", "dense", "label", "connected", "parallel", "self-loop"]);
for (const row of artifact.rows) assert.equal(row.probes.length, 3);
const dense = artifact.rows.find(({ fixture }) => fixture === "dense");
const label = artifact.rows.find(({ fixture }) => fixture === "label");
const connected = artifact.rows.find(({ fixture }) => fixture === "connected");
const canonical = artifact.rows.find(({ fixture }) => fixture === "canonical");
const selfLoop = artifact.rows.find(({ fixture }) => fixture === "self-loop");
assert.ok(dense.probeBest.screenAudit.fitScale >= dense.fitBudget);
assert.ok(dense.probeBest.visualRisk.totalLabelOverlapPairs < dense.currentSelected.visualRisk.totalLabelOverlapPairs);
assert.ok(label.probeBest.screenAudit.fitScale >= label.fitBudget);
assert.ok(label.probeBest.visualRisk.foreignRouteRelationLabelHits < label.currentSelected.visualRisk.foreignRouteRelationLabelHits);
assert.equal(connected.graph.components, 1);
assert.equal(connected.jointlySafeVariantCount, 0);
assert.ok(connected.probeBest.screenAudit.fitScale < connected.fitBudget || connected.probeBest.visualRisk.foreignRouteRelationLabelHits > connected.currentSelected.visualRisk.foreignRouteRelationLabelHits);
assert.equal(canonical.selectedForPreview.family, canonical.currentSelected.family);
assert.equal(selfLoop.selectedForPreview.family, selfLoop.currentSelected.family);
assert.equal(smoke.formalAcceptance, false);
assert.equal(smoke.cases.length, 6);
assert.equal(smoke.humanReview, "NOT READY");
console.log("bounded label-capacity screen/ownership refinement 1 audit: PASS");
